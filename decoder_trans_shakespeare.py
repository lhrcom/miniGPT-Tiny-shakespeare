import torch
import torch.nn as nn
import torch.nn.functional as F


torch.manual_seed(1337)

block_size = 256
batch_size = 64
n_embd = 384
eval_iters = 200
max_iters = 5000
device = 'cuda' if torch.cuda.is_available() else 'cpu'
learning_rate = 3e-4
dropout = 0.2
n_head = 6
n_layers = 6
eval_interval = 500
eval_iters = 200

with open('input.txt', 'r', encoding='utf-8') as f:
    text = f.read()

# 编写Tokenizer，文本和数字建立映射关系
chars = sorted(set(text))
vocab_size = len(chars)
# 构建字符到 Token ID 的映射
stoi = {}
for i,ch in enumerate(chars):
    stoi[ch] = i

# encode函数实现,文本转换为token id
def encoder(text):
  encoded_text = []
  for ch in text:
    encoded_text.append(stoi[ch])
  return encoded_text

# decoder函数实现,token id => 文本
itos = {}
for i,ch in enumerate(chars):
    itos[i] = ch

def decoder(text):
  decoder_text = []
  for i in text:
    decoder_text.append(itos[i])

  decoder_text = "".join(decoder_text)
  return decoder_text

data = torch.tensor(encoder(text), dtype=torch.long)
# data.shape
train_data = data[:int(0.9*len(data))]
val_data = data[int(0.9*len(data)):]

def get_batch(split):
  data = train_data if split == 'train' else val_data
  ix = torch.randint(0,len(data)-block_size,(batch_size,))
  x_list = []
  y_list = []
  for i in ix:
    x_list.append(data[i:i+block_size])
    y_list.append(data[i+1:i+block_size+1])
  x = torch.stack(x_list,dim=0)
  y = torch.stack(y_list,dim=0)
  # print(x.shape)
  # print(y.shape)
  x,y = x.to(device),y.to(device)
  return x,y #(B,T)

class Head(nn.Module):
  def __init__(self,head_size):
    super().__init__()
    self.key = nn.Linear(n_embd,head_size,bias=False)
    self.query = nn.Linear(n_embd,head_size,bias=False)
    self.value = nn.Linear(n_embd,head_size,bias=False)
    self.register_buffer('tril',torch.tril(torch.ones(block_size,block_size)))
    self.dropout = nn.Dropout(dropout)
  def forward(self,x):
    # x(B,T,C)
    B,T,C = x.shape
    k = self.key(x)
    q = self.query(x)
    v = self.value(x) #(B,T,hs)
    wei = q @ k.transpose(-2, -1)*k.shape[-1]**-0.5
    wei = wei.masked_fill(self.tril[:T,:T]==0, float('-inf'))
    wei = F.softmax(wei,dim=-1) #(B,T,T)
    wei = self.dropout(wei)
    out = wei @ v #(B,T,hs)
    return out

class MultiHead(nn.Module):
  def __init__(self,head_size,n_head):
    super().__init__()
    # head_size = n_embd // n_head
    self.heads = nn.ModuleList([Head(head_size) for _ in range (n_head)])
    self.proj = nn.Linear(head_size*n_head,n_embd)
    self.dropout = nn.Dropout(dropout)
  def forward(self,x):
    out = torch.cat([h(x) for h in self.heads],dim=-1)
    out = self.dropout(self.proj(out))
    return out #(B,T,C)

class FeedForward(nn.Module):
  def __init__(self,n_embd):
    super().__init__()
    self.net = nn.Sequential(
        nn.Linear(n_embd,4*n_embd),
        nn.ReLU(),
        nn.Linear(4*n_embd,n_embd),
        nn.Dropout(dropout)
    )
  def forward(self,x):
    return self.net(x)

class Block(nn.Module):
  def __init__(self):
    super().__init__()
    head_size = n_embd // n_head
    self.sa = MultiHead(head_size,n_head)
    self.ffwd = FeedForward(n_embd)
    self.layernorm1 = nn.LayerNorm(n_embd)
    self.layernorm2 = nn.LayerNorm(n_embd)
  def forward(self,x):
    x = x + self.sa(self.layernorm1(x))
    x = x + self.ffwd(self.layernorm2(x))
    return x #(B,T,C)

@torch.no_grad()
def estimate_loss():
  out = {}
  model.eval()
  for split in ['train','val']:
    losses = torch.zeros(eval_iters)
    for k in range(eval_iters):
      X,Y = get_batch(split)
      logits,loss = model(X,Y)
      losses[k] = loss.item()
    out[split] = losss.mean()
  model.train()
  return out

# embedding
class GPTModel(nn.Module):
  def __init__(self):
    super().__init__()
    self.token_embedding_table = nn.Embedding(vocab_size,n_embd)
    self.token_position_table = nn.Embedding(block_size,n_embd)
    self.blocks = nn.Sequential(*[Block() for _ in range(n_layers)])
    self.ln_f = nn.LayerNorm(n_embd)
    self.lm_head = nn.Linear(n_embd,vocab_size)
    self.apply(self._init_weights)

  def _init_weights(self, module):
        if isinstance(module, nn.Linear):
            torch.nn.init.normal_(module.weight, mean=0.0, std=0.02)
            if module.bias is not None:
                torch.nn.init.zeros_(module.bias)
        elif isinstance(module, nn.Embedding):
            torch.nn.init.normal_(module.weight, mean=0.0, std=0.02)

  def forward(self,idx,targets=None):
    B,T = idx.shape
    # idx[B,T]
    token_emd = self.token_embedding_table(idx)
    # token_emd[B,T,n_embd]
    position_emd = self.token_position_table(torch.arange(0,T,device=device))
    # position_emd[T,n_embd]
    x = token_emd + position_emd # (B,T,C)
    x = self.blocks(x)
    x = self.ln_f(x)
    logits = self.lm_head(x)
    if targets is None:
      loss = None
    else:
      B,T,C = logits.shape
      logits = logits.view(B*T,C)
      targets = targets.view(B*T)
      loss = F.cross_entropy(logits,targets)

    return logits,loss

  def generate(self,idx,max_token):
    for _ in range(max_token):
      idx_cond = idx[:,-block_size:]
      logits,loss = self(idx_cond)
      logits = logits[:,-1,:]
      probs = F.softmax(logits,dim=-1)
      idx_next = torch.multinomial(probs,num_samples=1)
      idx = torch.cat((idx,idx_next),dim=1)

    return idx

model = GPTModel()
m = model.to(device)
print(sum(p.numel() for p in m.parameters())/1e6,'M parameters')
optimizer = torch.optim.AdamW(model.parameters(),lr=learning_rate)

for iters in range(max_iters):

  if iters % eval_iters == 0 or iters == max_iters - 1:
    losses = estimate_loss()
    print(f"step: {iters}, train loss: {losses['train']}, val loss: {losses['val']}")

  xb,yb = get_batch('train')
  logits, loss = model(xb,yb)
  optimizer.zero_grad(set_to_none=True)
  # set_to_none 节省内存
  loss.backward()
  optimizer.step()

context = torch.zeros((1,1),dtype=torch.long,device=device)
print(decoder(m.generate(context,max_token=500)[0].tolist()))
